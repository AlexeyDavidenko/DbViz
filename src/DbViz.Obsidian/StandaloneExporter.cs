using System.Globalization;
using System.IO.Compression;
using System.Text;
using DbViz.Core;
using DbViz.Core.Model;

namespace DbViz.Obsidian;

public sealed record ExportResult(string VaultDir, string ZipPath, int Notes, int ManualNotesCarried);

/// <summary>
/// Ready-to-open standalone vault for other people: schema notes (with the owner's manual edits),
/// its own .obsidian (layer colors, arrows, preset bookmarks), a start page, an installer and a zip archive.
/// </summary>
public static class StandaloneExporter
{
    public const string Section = "DBVisualization";
    public const string HomeNote = "Start here.md";
    public const string InstallFolder = "_Install";
    public const string ReadmeFile = "HOW TO INSTALL.txt";
    public const string MacInstaller = "Install into my vault (macOS).command";
    public const string WindowsInstaller = "Install into my vault (Windows).cmd";
    private const string Marker = ".dbviz-export";

    /// <param name="sourceSchemaDir">Schema section in the owner's vault (.../Databases/HR), source of manual edits; may not exist.</param>
    /// <param name="outDir">Folder where &lt;name&gt;/ and &lt;name&gt;.zip are created.</param>
    public static ExportResult Export(Snapshot snapshot, string? sourceSchemaDir, string outDir, RenderOptions? options, ILog log,
        IndexOptions? indexOptions = null)
    {
        var name = $"DbViz-{snapshot.Schema}";
        var vaultDir = Path.GetFullPath(Path.Combine(outDir, name));
        PrepareTarget(vaultDir);

        // 1. owner's manual edits: copy their section first, then rendering rewrites only the AUTO blocks
        var schemaDir = Path.Combine(vaultDir, Section, snapshot.Schema);
        var carried = 0;
        if (sourceSchemaDir is not null && Directory.Exists(sourceSchemaDir))
        {
            foreach (var file in Directory.EnumerateFiles(sourceSchemaDir, "*.md", SearchOption.AllDirectories))
            {
                var rel = Path.GetRelativePath(sourceSchemaDir, file).Replace('\\', '/');
                if (rel.StartsWith(VaultLayout.ArchiveFolder + "/", StringComparison.Ordinal)) continue; // the owner's archive is not shared
                var target = Path.Combine(schemaDir, Path.GetRelativePath(sourceSchemaDir, file));
                Directory.CreateDirectory(Path.GetDirectoryName(target)!);
                File.Copy(file, target);
                if (HasManualText(File.ReadAllText(file))) carried++;
            }
            log.Info($"Copied the owner's notes from {sourceSchemaDir} (with manual text: {carried})");
        }

        // 2. render for the standalone vault layout
        ObsidianRenderer.Render(snapshot, vaultDir, Section, options, log, indexOptions);

        // 3. start page, Obsidian settings, installer
        var sectionPath = $"{Section}/{snapshot.Schema}";
        File.WriteAllText(Path.Combine(vaultDir, HomeNote), Home(snapshot), new UTF8Encoding(false));
        ObsidianConfigWriter.WriteStandalone(vaultDir, snapshot.Schema, [HomeNote, $"{sectionPath}/{snapshot.Schema}.md"]);
        WriteInstaller(vaultDir, snapshot.Schema);
        File.WriteAllText(Path.Combine(vaultDir, Marker), $"Generated by DbViz {DateTime.Now:yyyy-MM-dd HH:mm}. This folder is recreated by the export command.\n");

        // 4. archive
        var zipPath = Path.Combine(outDir, $"{name}-{snapshot.ExtractedAt:yyyyMMdd}.zip");
        if (File.Exists(zipPath)) File.Delete(zipPath);
        ZipFile.CreateFromDirectory(vaultDir, zipPath, CompressionLevel.Optimal, includeBaseDirectory: true);

        var notes = Directory.EnumerateFiles(vaultDir, "*.md", SearchOption.AllDirectories).Count();
        log.Info($"Standalone vault: {vaultDir} ({notes} notes), archive: {zipPath} ({new FileInfo(zipPath).Length / 1024.0 / 1024.0:F1} MB)");
        return new ExportResult(vaultDir, zipPath, notes, carried);
    }

    /// <summary>Recreates only our own export folder (identified by a marker); never touches a foreign folder.</summary>
    private static void PrepareTarget(string vaultDir)
    {
        if (Directory.Exists(vaultDir))
        {
            if (!File.Exists(Path.Combine(vaultDir, Marker)))
                throw new InvalidOperationException($"Folder {vaultDir} exists and was not created by export; choose another --out.");
            Directory.Delete(vaultDir, recursive: true);
        }
        Directory.CreateDirectory(vaultDir);
    }

    private static bool HasManualText(string note)
    {
        foreach (var heading in Note.LegacyManualHeadings.Prepend(Note.ManualHeading))
        {
            var i = note.IndexOf(heading + "\n", StringComparison.Ordinal);
            if (i < 0) continue;
            var rest = note[(i + heading.Length)..];
            var end = rest.IndexOf("%% AUTO:BEGIN", StringComparison.Ordinal);
            var section = end < 0 ? rest : rest[..end];
            foreach (var placeholder in Note.LegacyManualPlaceholders.Prepend(Note.ManualPlaceholder))
                section = section.Replace(placeholder, "");
            return section.Trim().Length > 0;
        }
        return false;
    }

    /// <summary>Installer for an existing vault: settings payload + scripts for macOS (JXA) and Windows (PowerShell).</summary>
    private static void WriteInstaller(string vaultDir, string schema)
    {
        var dir = Path.Combine(vaultDir, InstallFolder);
        Directory.CreateDirectory(dir);
        var utf8 = new UTF8Encoding(false);

        var payload = ObsidianConfigWriter.InstallerPayload(schema, Section);
        File.WriteAllText(Path.Combine(dir, "dbviz-obsidian-settings.json"), payload.ToJsonString(ObsidianConfigWriter.Json), utf8);
        File.WriteAllText(Path.Combine(dir, "install.js"), Resource("install.js"), utf8);
        // Windows PowerShell 5.1 reads a .ps1 without BOM as ANSI and breaks non-ASCII text, hence the BOM
        File.WriteAllText(Path.Combine(dir, "install.ps1"), Resource("install.ps1"), new UTF8Encoding(true));

        var mac = Path.Combine(dir, MacInstaller);
        File.WriteAllText(mac, "#!/bin/bash\n# DbViz: install notes and graph settings into an existing Obsidian vault\n" +
                               "DIR=\"$(cd \"$(dirname \"$0\")\" && pwd)\"\n" +
                               "osascript -l JavaScript \"$DIR/install.js\" \"$DIR\" \"$@\"\n" +
                               "echo; read -n 1 -s -r -p \"Press any key to close this window...\"\n", utf8);
        if (!OperatingSystem.IsWindows())
            File.SetUnixFileMode(mac, UnixFileMode.UserRead | UnixFileMode.UserWrite | UnixFileMode.UserExecute |
                                      UnixFileMode.GroupRead | UnixFileMode.GroupExecute | UnixFileMode.OtherRead | UnixFileMode.OtherExecute);

        File.WriteAllText(Path.Combine(dir, WindowsInstaller),
            "@echo off\r\nchcp 65001 >nul\r\npowershell -NoProfile -ExecutionPolicy Bypass -File \"%~dp0install.ps1\" %*\r\npause\r\n", utf8);

        var group = ObsidianConfigWriter.BookmarkGroupTitle(schema);
        File.WriteAllText(Path.Combine(vaultDir, ReadmeFile), $"""
            DbViz - Obsidian documentation of the {schema} schema
            =====================================================

            OPTION 1 (easiest) - open as a separate vault
              1. Unzip the archive.
              2. Obsidian -> "Open folder as vault" -> choose the DbViz-{schema} folder.
              Layer colors, arrows and the "{group}" bookmarks are there right away.

            OPTION 2 - add to your existing vault
              Simply copying the folder does NOT bring the colors and bookmarks along: they live in the hidden
              .obsidian folder of your vault. Use the installer from the "{InstallFolder}" folder:
              1. Quit Obsidian.
              2. macOS:   double-click "{MacInstaller}"
                          (if macOS refuses to open it: right-click -> Open -> Open).
                 Windows: double-click "{WindowsInstaller}".
              3. Pick your vault folder. The installer copies the notes (folder {Section}) and adds the
                 layer colors and bookmarks. Your own settings and bookmarks are kept; backups are made.
              4. Open Obsidian -> Bookmarks panel -> group "{group}".

            No community plugins are needed - only built-in Obsidian features.
            """.Replace("\n", Environment.NewLine), utf8);
    }

    private static string Resource(string name)
    {
        using var s = typeof(StandaloneExporter).Assembly.GetManifestResourceStream($"DbViz.Installer.{name}")
                      ?? throw new InvalidOperationException($"Embedded resource {name} not found");
        using var r = new StreamReader(s, Encoding.UTF8);
        return r.ReadToEnd();
    }

    private static string Home(Snapshot s)
    {
        var ix = new SchemaIndex(s);
        var counts = string.Join("\n", ix.Objects.GroupBy(o => o.Kind).OrderBy(g => g.Key)
            .Select(g => $"| {KindInfo.LayerTitle(KindInfo.LayerOf(g.Key))} | {KindInfo.Plural(g.Key)} | {g.Count()} |"));
        var presets = string.Join("\n", GraphPresets.For(s.Schema).Select(p => $"| {p.Title} | {p.What} |"));
        var group = ObsidianConfigWriter.BookmarkGroupTitle(s.Schema);
        return $"""
            ---
            tags: [dbviz]
            ---
            # {s.Schema} schema documentation

            > [!info] Extracted {s.ExtractedAt.ToString("yyyy-MM-dd HH:mm", CultureInfo.InvariantCulture)} · {s.DbVersion}
            > Generated by DbViz from the Oracle data dictionary (metadata only, no table data). Objects: {ix.Objects.Count}, relationships: {ix.Edges.Count}.

            ## Where to start
            - [[{s.Schema}]] — schema home: layers, counts, indexes, quality reports
            - **Bookmarks** panel (left) → group "{group}" — ready-made graph views
            - **Graph** (Cmd/Ctrl+G) is preconfigured: colors by layer, arrows = dependency direction
            - Relationships of a single object are in its note: the "Relationships" section, diagrams and "Open local graph"

            ## Layers and colors
            | Layer | Objects | Color |
            |---|---|---|
            | L0 Storage | tables, sequences | blue |
            | L1 Access | views, synonyms | green |
            | L2 Logic | packages, procedures, functions, triggers | orange |
            | L3 Types & integration | types, DB links, jobs | purple |

            ## Contents
            | Layer | Type | Count |
            |---|---|---|
            {counts}

            ## Graph views (bookmarks)
            | View | What you see |
            |---|---|
            {presets}

            ## How to open
            **As a separate vault (easiest):** unzip the archive → Obsidian → **Open folder as vault** → folder `DbViz-{s.Schema}`.

            **In your existing vault:** copying the folder does not bring the colors and bookmarks along (they live in the hidden
            `.obsidian` of your vault). Quit Obsidian and run the installer from the `{InstallFolder}` folder:
            "{MacInstaller}" or "{WindowsInstaller}" → pick your vault. Details: `{ReadmeFile}`.

            No community plugins are needed — built-in Obsidian features are enough.

            > [!note] Notes are a snapshot as of the extraction date. You can add your own remarks in the "Notes" section of any note.
            """;
    }
}
